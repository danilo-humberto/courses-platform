begin;
create function public.test_assert(ok boolean, msg text) returns void language plpgsql as $$ begin if ok is distinct from true then raise exception 'ASSERT: %',msg; end if; end $$;
update public.profiles set active=true where id in ('10000000-0000-4000-8000-000000000001','10000000-0000-4000-8000-000000000002');
select set_config('request.jwt.claim.sub','10000000-0000-4000-8000-000000000001',true);
create temp table certificate_fixture as select public.admin_save_draft(null,'{"title":"Certificado sintético","quiz_enabled":false,"pass_score":70,"max_attempts":2,"questions":[]}') as result;
select public.set_draft_pdf('10000000-0000-4000-8000-000000000001',(result->>'version_id')::uuid,'test/certificate-course.pdf',1) from certificate_fixture;
select public.set_draft_certificate('10000000-0000-4000-8000-000000000001',(result->>'version_id')::uuid,
  jsonb_build_object('path','templates/'||(result->>'version_id')||'/example.pdf','hours','4 horas','fields',
  '[{"key":"nome","x":0.1,"y":0.5,"width":0.8,"size":24,"color":"#152D40","align":"center"},{"key":"cpf","x":0.1,"y":0.6,"width":0.8,"size":12,"color":"#152D40","align":"center"}]'::jsonb)) from certificate_fixture;
select public.admin_publish((result->>'version_id')::uuid) from certificate_fixture;
select public.admin_assign((result->>'version_id')::uuid,array['10000000-0000-4000-8000-000000000002'::uuid]) from certificate_fixture;
select public.test_assert((select count(*) from public.certificates)=0,'no certificate before completion');
update public.profiles set name='Nome original',cpf='00000000000' where id='10000000-0000-4000-8000-000000000002';
select set_config('request.jwt.claim.sub','10000000-0000-4000-8000-000000000002',true);
select public.training_view(a.id,1) from public.assignments a join certificate_fixture f on a.version_id=(f.result->>'version_id')::uuid;
select public.training_complete(a.id) from public.assignments a join certificate_fixture f on a.version_id=(f.result->>'version_id')::uuid;
select public.training_complete(a.id) from public.assignments a join certificate_fixture f on a.version_id=(f.result->>'version_id')::uuid;
select public.test_assert((select count(*) from public.certificates)=1,'one certificate per completion');
select public.test_assert((select values->>'nome' from public.certificates)='Nome original','snapshot name');
select public.test_assert((select values->>'cpf' from public.certificates)='00000000000','snapshot CPF');
update public.profiles set name='Nome alterado',cpf=null where id='10000000-0000-4000-8000-000000000002';
select public.test_assert((select values->>'nome' from public.certificates)='Nome original','snapshot immutable after profile edit');
set local role authenticated;
select public.test_assert((select count(*) from public.certificates)=1,'owner sees own certificate');
select public.test_assert(not has_table_privilege('authenticated','public.certificates','INSERT'),'cannot forge certificate');
select public.test_assert(not has_table_privilege('authenticated','public.certificates','UPDATE'),'cannot edit snapshot');
select public.test_assert(not has_function_privilege('authenticated','public.set_draft_certificate(uuid,uuid,jsonb)','EXECUTE'),'client cannot forge template path');
select set_config('request.jwt.claim.sub','10000000-0000-4000-8000-000000000003',true);
select public.test_assert((select count(*) from public.certificates)=0,'other participant denied');
select set_config('request.jwt.claim.sub','10000000-0000-4000-8000-000000000001',true);
select public.test_assert((select count(*) from public.certificates)=1,'administrator sees certificate');
select public.admin_clear_reports('EXCLUIR TUDO');
select public.test_assert((select count(*) from public.certificates)=1,'report cleanup preserves certificate');
reset role;
select public.admin_delete_course((result->>'course_id')::uuid,true) from certificate_fixture;
select public.test_assert((select count(*) from public.certificates)=1,'course deletion preserves certificate');
update public.profiles set active=false where id='10000000-0000-4000-8000-000000000002';
set local role authenticated;
select set_config('request.jwt.claim.sub','10000000-0000-4000-8000-000000000002',true);
select public.test_assert((select count(*) from public.certificates)=0,'inactive owner denied');
reset role;
do $$
declare d jsonb; vid uuid; aid uuid; qid uuid; cfg jsonb; r jsonb;
begin
  perform set_config('request.jwt.claim.sub','10000000-0000-4000-8000-000000000001',true);
  d:=public.admin_save_draft(null,'{"title":"Quiz certificado","quiz_enabled":true,"pass_score":70,"max_attempts":2,"questions":[{"prompt":"Teste","options":["Sim","Não"],"correct_index":0}]}');
  vid:=(d->>'version_id')::uuid;
  select template into cfg from public.certificates limit 1;
  cfg:=jsonb_set(cfg,'{path}',to_jsonb('templates/'||vid::text||'/quiz.pdf'));
  perform public.set_draft_pdf('10000000-0000-4000-8000-000000000001',vid,'test/quiz.pdf',1);
  perform public.set_draft_certificate('10000000-0000-4000-8000-000000000001',vid,cfg);
  perform public.admin_publish(vid);
  perform public.admin_assign(vid,array['10000000-0000-4000-8000-000000000003'::uuid]);
  select id into aid from public.assignments where version_id=vid;
  select id into qid from public.questions where version_id=vid;
  perform set_config('request.jwt.claim.sub','10000000-0000-4000-8000-000000000003',true);
  perform public.training_view(aid,1);
  r:=public.training_submit(aid,gen_random_uuid(),jsonb_build_object(qid::text,1));
  perform public.test_assert(not exists(select 1 from public.certificates where assignment_id=aid),'failed quiz has no certificate');
  r:=public.training_submit(aid,gen_random_uuid(),jsonb_build_object(qid::text,0));
  perform public.test_assert(exists(select 1 from public.certificates where assignment_id=aid and values->>'cpf' is null),'passed quiz issues certificate without CPF');
end $$;
rollback;
